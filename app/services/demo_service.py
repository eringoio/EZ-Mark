"""Synthetic demo mode: seeding, resets, and hosted-demo upload guards.

Demo mode (``DEMO_MODE=1``) runs the same application against a *separate* demo
data root (``DEMO_DATA_ROOT``, default ``data-demo/`` with its own
``data-demo/app.sqlite``), so a public demo instance never touches a school's
real local dataset.

Demo content is fully synthetic: fictional participants ("Demo Class A/B"),
a fictional answer key, and no scan images. Everything is created through the
regular exam/template/roster services — never real data, never imported.

Hosted-demo safety rules enforced here:

* roster CSV/XLSX imports, portable package imports, and scan uploads are
  rejected with a clear localized message (``demo.upload_disabled``);
* normal local mode (``DEMO_MODE`` off) is completely unaffected.
"""

