def is_demo_mode() -> bool:
    return get_settings().demo_mode


def ensure_uploads_allowed() -> None:
    """Guard for persistent upload/import endpoints.

    In demo mode these endpoints are rejected so a shared public demo cannot
    become a place where visitors upload personal data or arbitrary packages.
    """
    if is_demo_mode():
        raise HTTPException(status_code=403, detail=_("demo.upload_disabled"))


def demo_is_seeded(db: Session) -> bool:
    """True when the demo database already contains the seeded example set."""

    from app.models import MockExam, Question

    template = db.scalar(
        select(MockExam).where(
            MockExam.is_template.is_(True),
            MockExam.name == DEMO_TEMPLATE_NAME,
        )
    )
    if template is None:
        return False
    return (
        db.scalar(select(func.count()).select_from(Question).where(Question.exam_id == template.id))
        == len(DEMO_ANSWER_KEY)
    )


def _wipe_demo_database() -> None:
    """Delete every table row (schema marker excepted) from the demo database."""
    from app.database import Base, engine

    with engine.begin() as connection:
        # Reversed sorted_tables deletes children before parents.
        for table in reversed(Base.metadata.sorted_tables):
            if table.name == "schema_info":
                continue
            connection.execute(text(f'DELETE FROM "{table.name}"'))


def wipe_demo_data() -> None:
    """Empty the demo database and demo file storage. Requires DEMO_MODE."""
    settings = get_settings()
    if not settings.demo_mode:
        raise RuntimeError("Demo wipe requires DEMO_MODE to be enabled.")
    _wipe_demo_database()
    for directory in ("generated_pdfs", "uploaded_scans", "processed_pages", "review_crops"):
        _clear_directory(settings.data_root / directory)


def _clear_directory(directory: Path) -> None:
    if not directory.exists():
        return
    for entry in directory.iterdir():
        if entry.is_dir():
            import shutil

            shutil.rmtree(entry, ignore_errors=True)
        else:
            entry.unlink(missing_ok=True)


def reset_demo_data() -> bool:
    """Wipe and reseed the demo environment. Returns True when seeding happened."""
    wipe_demo_data()
    from app.database import SessionLocal

    with SessionLocal() as db:
        return seed_demo_data(db)


def seed_demo_data(db: Session, *, force: bool = False) -> bool:
    """Seed the synthetic demo dataset once.

    Idempotent: a second call without ``force`` (i.e. already seeded) changes
    nothing and returns ``False``. With ``force=True`` the demo tables are wiped
    first and the dataset is recreated deterministically.
    """
    if not force and demo_is_seeded(db):
        return False

    from app.services.student_import_service import (
        import_preview_to_payload,
        import_students_from_payload,
        validate_student_rows,
    )
    from app.services.test_template_service import (
        BuilderGroupInput,
        BuilderQuestionInput,
        BuilderSheetInput,
        TemplateCreateInput,
        create_blank_template,
        create_run_from_template,
        save_template_builder,
    )

    # --- 20-question Multiple-Choice quiz template --------------------------
    template = create_blank_template(
        db,
        TemplateCreateInput(
            name=DEMO_TEMPLATE_NAME,
            assessment_type="generic_test",
            scoring_mode="raw_score",
            numbering_mode="continuous",
            template_description=DEMO_TEMPLATE_DESCRIPTION,
        ),
    )
    sheet = template.physical_sheets[0]
    section = template.scoring_sections[0]
    questions = [
        BuilderQuestionInput(
            id=None,
            number_label=None,
            correct_answer=DEMO_ANSWER_KEY[index - 1],
            choice_count=4,
            points=1,
            scoring_section_id=section.id,
        )
        for index in range(1, 21)
    ]
    save_template_builder(
        db,
        template,
        [
            BuilderSheetInput(
                id=sheet.id,
                sheet_name=sheet.sheet_name,
                groups=[
                    BuilderGroupInput(
                        id=None,
                        problem_title="Demo problems",
                        questions=questions,
                    )
                ],
            )
        ],
    )

    run = create_run_from_template(db, template, DEMO_RUN_NAME, DEMO_EXAM_DATE)

    # --- Peer Evaluation Example (optional, uses the verified services) -----
    peer_template = create_blank_template(
        db,
        TemplateCreateInput(
            name=DEMO_PEER_TEMPLATE_NAME,
            assessment_type="peer_review",
            scoring_mode="raw_score",
            numbering_mode="continuous",
            template_description=DEMO_TEMPLATE_DESCRIPTION,
        ),
    )
    peer_run = create_run_from_template(db, peer_template, DEMO_PEER_RUN_NAME)

    # --- Fictional participants, attached to both runs ----------------------
    roster = [
        {"student_number": number, "name": name, "class_name": class_name}
        for number, name, class_name in DEMO_STUDENTS
    ]
    for exam in (run, peer_run):
        preview = validate_student_rows(roster, db, exam)
        payload = import_preview_to_payload(preview)
        import_students_from_payload(db, exam, payload)
        if exam is peer_run:
            from app.services.peer_review_builder_service import sync_peer_review_targets

            sync_peer_review_targets(db, exam)

    db.commit()
    return True


def reset_demo_on_start() -> None:
    """Startup hook: wipe and reseed when DEMO_RESET_ON_START is enabled."""
    settings = get_settings()
    if settings.demo_mode and settings.demo_reset_on_start:
        reset_demo_data()
